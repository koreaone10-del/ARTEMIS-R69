/* aw_get_stackinfo, fel.c L824-875 ("works everywhere" branch):
 * reads sp_irq and sp via CPSR mode switching. Upstream uses the
 * values only for logging, so a failure here is logged as a
 * warning step and does not abort the run. */
static int get_stackinfo(fel_device *dev, uint32_t *sp_irq, uint32_t *sp)
{
    unsigned char code[36], res[8];
    fel_put_le32(code + 0, 0xe10f0000u); /* mrs r0, CPSR */
    fel_put_le32(code + 4, 0xe3c0101fu); /* bic r1, r0, #31 */
    fel_put_le32(code + 8, 0xe3811012u); /* orr r1, r1, #18 */
    fel_put_le32(code + 12, 0xe121f001u); /* msr CPSR_c, r1 */
    fel_put_le32(code + 16, 0xe1a0100du); /* mov r1, sp */
    fel_put_le32(code + 20, 0xe121f000u); /* msr CPSR_c, r0 */
    fel_put_le32(code + 24, 0xe58f1004u); /* str r1, [pc, #4] */
    fel_put_le32(code + 28, 0xe58fd004u); /* str sp, [pc, #4] */
    fel_put_le32(code + 32, 0xe12fff1eu); /* bx lr */
    if (fel_write_mem(dev, H3_SCRATCH_ADDR, code, sizeof(code)) != 0)
        return -1;
    if (fel_exec_mem(dev, H3_SCRATCH_ADDR) != 0)
        return -1;
    if (fel_read_mem(dev, H3_SCRATCH_ADDR + 0x24, res, sizeof(res)) != 0)
        return -1;
    *sp_irq = fel_get_le32(res + 0);
    *sp = fel_get_le32(res + 4);
    return 0;
}

/* aw_generate_mmu_translation_table, fel.c L914-931:
 * direct 1 MiB section mapping, TEXCB=00000 (strongly ordered)
 * except the first and last sections (TEXCB=00100, normal). */
static void generate_mmu_tt(uint32_t tt[4096])
{
    uint32_t i;
    for (i = 0; i < 4096; i++)
        tt[i] = 0x00000DE2u | (i << 20);
    tt[0x000] |= 0x1000u;
    tt[0xFFF] |= 0x1000u;
}

/* aw_backup_and_disable_mmu, fel.c L933-1016.
 * Returns: 1 if the BROM MMU was enabled and a table was read
 * (tt_out holds the 16 KiB table, host-endian words), 0 if the
 * MMU was not enabled (tt_out untouched), -1 on error.
 * For H3 the BROM does not enable the MMU (fel.c L457-460), so
 * the expected result is 0 with the SCTLR check passing. */
static int backup_and_disable_mmu(fel_device *dev, uint32_t tt[4096],
                                  uint32_t *sctlr_out)
{
    uint32_t sctlr, dacr, ttbcr, ttbr0, i;
    /* v3.1: off the stack (static storage; single-threaded tool).
     * v3 had this 16 KiB buffer on the stack, nested under main's
     * own 16 KiB tt[4096] — the largest latent stack risk. */
    static unsigned char raw[16384];
    /* fel.c L975-980: ignore M/Z/I/V/UNK bits, expect no TEX remap. */
    if (get_sctlr(dev, &sctlr) != 0)
        return -1;
    *sctlr_out = sctlr;
    if ((sctlr & ~((0x7u << 11) | (1u << 6) | 1u)) != 0x00C50038u)
        return -2; /* unexpected SCTLR */
    if (!(sctlr & 1u))
        return 0; /* "MMU is not enabled by BROM", fel.c L983-986 */
    if (get_dacr(dev, &dacr) != 0 || dacr != 0x55555555u)
        return -1;
    if (get_ttbcr(dev, &ttbcr) != 0 || ttbcr != 0x00000000u)
        return -1;
    if (get_ttbr0(dev, &ttbr0) != 0 || (ttbr0 & 0x3FFFu) != 0)
        return -1;
    if (fel_read_mem(dev, ttbr0, raw, sizeof(raw)) != 0)
        return -1;
    for (i = 0; i < 4096; i++)
        tt[i] = fel_get_le32(raw + i * 4);
    for (i = 0; i < 4096; i++) {
        if (((tt[i] >> 1) & 1u) != 1u || ((tt[i] >> 18) & 1u) != 0u)
            return -1; /* not a section descriptor */
        if ((tt[i] >> 20) != i)
            return -1; /* not a direct mapping */
    }
    /* Disable I-cache, MMU and branch prediction, fel.c L945-958. */
    {
        unsigned char code[24];
        fel_put_le32(code + 0, 0xee110f10u); /* mrc 15,0,r0,cr1,cr0,{0} */
        fel_put_le32(code + 4, 0xe3c00001u); /* bic r0, r0, #1 */
        fel_put_le32(code + 8, 0xe3c00a01u); /* bic r0, r0, #4096 */
        fel_put_le32(code + 12, 0xe3c00b02u); /* bic r0, r0, #2048 */
        fel_put_le32(code + 16, 0xee010f10u); /* mcr 15,0,r0,cr1,cr0,{0} */
        fel_put_le32(code + 20, 0xe12fff1eu); /* bx lr */
        if (fel_write_mem(dev, H3_SCRATCH_ADDR, code, sizeof(code)) != 0)
            return -1;
        if (fel_exec_mem(dev, H3_SCRATCH_ADDR) != 0)
            return -1;
    }
    return 1;
}

/* aw_restore_and_enable_mmu, fel.c L1018-1076.
 * Writes the (tweaked) table back to the current TTBR0 and
 * enables I-cache, MMU and branch prediction via scratch code.
 * Deviation note: upstream writes to whatever TTBR0 reads as;
 * this tool refuses a TTBR0 of 0 rather than writing a table
 * to address 0. */
static int restore_and_enable_mmu(fel_device *dev, uint32_t tt[4096])
{
    uint32_t ttbr0, i;
    /* v3.1: off the stack, same reason as backup_and_disable_mmu. */
    static unsigned char raw[16384];
    unsigned char code[48];
    if (get_ttbr0(dev, &ttbr0) != 0)
        return -1;
    if (ttbr0 == 0)
        return -2; /* refusing to write a table to address 0 */
    for (i = (H3_DRAM_BASE >> 20); i < ((H3_DRAM_BASE + DRAM_SIZE) >> 20); i++) {
        tt[i] &= ~((7u << 12) | (1u << 3) | (1u << 2));
        tt[i] |= (1u << 12); /* TEXCB 00100, normal uncached */
    }
    tt[0xFFF] &= ~((7u << 12) | (1u << 3) | (1u << 2));
    tt[0xFFF] |= (1u << 12) | (1u << 3) | (1u << 2); /* cached BROM */
    for (i = 0; i < 4096; i++)
        fel_put_le32(raw + i * 4, tt[i]);
    if (fel_write_mem(dev, ttbr0, raw, sizeof(raw)) != 0)
        return -1;
    fel_put_le32(code + 0, 0xe3a00000u); /* mov r0, #0 */
    fel_put_le32(code + 4, 0xee080f17u); /* mcr 15,0,r0,cr8,cr7,{0} */
    fel_put_le32(code + 8, 0xee070f15u); /* mcr 15,0,r0,cr7,cr5,{0} */
    fel_put_le32(code + 12, 0xee070fd5u); /* mcr 15,0,r0,cr7,cr5,{6} */
    fel_put_le32(code + 16, 0xf57ff04fu); /* dsb sy */
    fel_put_le32(code + 20, 0xf57ff06fu); /* isb sy */
    fel_put_le32(code + 24, 0xee110f10u); /* mrc 15,0,r0,cr1,cr0,{0} */
    fel_put_le32(code + 28, 0xe3800001u); /* orr r0, r0, #1 */
    fel_put_le32(code + 32, 0xe3800a01u); /* orr r0, r0, #4096 */
    fel_put_le32(code + 36, 0xe3800b02u); /* orr r0, r0, #2048 */
    fel_put_le32(code + 40, 0xee010f10u); /* mcr 15,0,r0,cr1,cr0,{0} */
    fel_put_le32(code + 44, 0xe12fff1eu); /* bx lr */
    if (fel_write_mem(dev, H3_SCRATCH_ADDR, code, sizeof(code)) != 0)
        return -1;
    return fel_exec_mem(dev, H3_SCRATCH_ADDR);
}

/* ---------- main flow ----------
 * Order follows fel.c exactly:
 *   validate file (L1097-1117) -> FEL_VERSION / soc check (L641-663)
 *   -> stackinfo (L1129, logging only) -> MMU backup (L1132)
 *   -> MMU setup for H3 (L1133-1150) -> SPL piece writes (L1151-1175)
 *   -> SPL limit check (L1177-1187) -> remaining SPL write (L1189)
 *   -> thunk build/write/exec (L1190-1213) -> 250 ms wait (L1216)
 *   -> eGON.FEL read-back (L1219-1225) -> MMU restore (L1227-1228)
 *   -> U-Boot staging (aw_fel_write_uboot_image, L1238-1296)
 *   -> U-Boot exec (fel.c L1748-1763, "uboot" command) */

static char g_error[512];
static int g_failed = 0;

#define CHECK(cond, msg) do { \
    if (!(cond)) { snprintf(g_error, sizeof(g_error), "%s", (msg)); g_failed = 1; goto out; } \
} while (0)

#define STEP(name, ok, detail) step_log((name), (ok), (detail))

int main(int argc, char **argv)
{
    const char *tool = "fel_spl_uboot";
    char *params[1];
    const char *flags[4];
    static const char *env_names[1] = { "FEL_FILE" };
    int fd = -1, i;
    unsigned char *file = NULL;
    size_t file_len = 0;
    char file_sha[65] = "";
    char spl_sha[65] = "";
    uint32_t spl_len = 0, spl_len_limit = H3_SPL_LEN_LIMIT;
    uint32_t uboot_load = 0, uboot_ep = 0, uboot_size = 0;
    uint16_t soc_id_checked = 0;
    fel_device dev;
    int dev_open = 0;
    char err[256];
    int rc = 1;

    /* v3.1: unbuffered stdout — every progress line reaches the
     * pipe the moment it is printed, even if the process is
     * killed afterwards. Without this, a kill loses everything
     * buffered since the last fflush. */
    setvbuf(stdout, NULL, _IONBF, 0);
    memset(&dev, 0, sizeof(dev));

    if (fel_resolve_fd_and_params(argc, argv, 1, params, flags, 4,
                                  env_names, &fd) != 0) {
        fel_print_error(tool,
            "usage: fel_spl_uboot [--validate-only] <fd> <u-boot-sunxi-with-spl.bin>");
        return 2;
    }
    for (i = 0; flags[i]; i++) {
        if (strcmp(flags[i], "--validate-only") == 0)
            g_validate_only = 1;
    }
    {
        const char *env_vo = getenv("FEL_VALIDATE_ONLY");
        if (env_vo && strcmp(env_vo, "1") == 0)
            g_validate_only = 1;
    }

    /* ---- validate the file BEFORE touching the device ---- */
    file = read_all_file(params[0], &file_len);
    CHECK(file != NULL, "cannot open input file (or file is over 2 MiB)");
    CHECK(file_len <= UB_MAX_FILE, "file too large (refusing files over 2 MiB)");
    fel_sha256_hex(file, file_len, file_sha);
    {
        char d[128];
        snprintf(d, sizeof(d), "size %u bytes, sha256 %s",
                 (unsigned)file_len, file_sha);
        STEP("validate_file_size", 1, d);
    }
    CHECK(file_len > H3_SPL_LEN_LIMIT,
          "no U-Boot proper in file: file must be a full u-boot-sunxi-with-spl.bin larger than 32768 bytes");
    CHECK(file_len >= 32 && memcmp(file + 4, "eGON.BT0", 8) == 0,
          "SPL: eGON header is not found (fel.c L1097)");
    spl_len = fel_get_le32(file + 16);
    {
        char d[128];
        snprintf(d, sizeof(d), "eGON.BT0 at offset 4, spl_len %u",
                 spl_len);
        STEP("validate_egon_header", 1, d);
    }
    CHECK(spl_len <= file_len && (spl_len % 4) == 0,
          "SPL: bad length in the eGON header (fel.c L1106)");
    CHECK(spl_len <= H3_SPL_LEN_LIMIT,
          "SPL: too large (need spl_len <= 32768, fel.c L1181)");
    CHECK(egon_checksum_ok(file, spl_len),
          "SPL: checksum check failed (fel.c L1110-1117)");
    fel_sha256_hex(file, spl_len, spl_sha);
    STEP("validate_egon_checksum", 1, "checksum 2*buf32[3]-0x5F0A6C39 minus word sum == 0");
    /* U-Boot proper header at offset SPL_LEN_LIMIT, fel.c L1241-1294. */
    {
        const unsigned char *h = file + H3_SPL_LEN_LIMIT;
        size_t rem = file_len - H3_SPL_LEN_LIMIT;
        uint32_t data_size;
        CHECK(rem > HEADER_SIZE, "Invalid U-Boot image: bad size or signature");
        CHECK(be32(h + 0) == IH_MAGIC, "Invalid U-Boot image: bad magic (expected 0x27051956)");
        CHECK(h[29] == IH_ARCH_ARM, "Invalid U-Boot image: wrong architecture (expected ARM)");
        CHECK(h[30] == IH_TYPE_FIRMWARE, "U-Boot image type mismatch: expected IH_TYPE_FIRMWARE");
        data_size = be32(h + 12);
        CHECK(data_size == rem - HEADER_SIZE,
              "U-Boot image data size mismatch");
        uboot_load = be32(h + 16);
        uboot_ep = be32(h + 20);
        uboot_size = data_size;
        CHECK(uboot_load >= H3_DRAM_BASE &&
              uboot_load < H3_DRAM_BASE + DRAM_SIZE &&
              (uint64_t)uboot_load + uboot_size <=
                  (uint64_t)H3_DRAM_BASE + DRAM_SIZE,
              "U-Boot load address is outside DRAM");
        {
            char d[192];
            snprintf(d, sizeof(d),
                     "mkimage header ok, load 0x%08x, entry 0x%08x, payload %u bytes",
                     uboot_load, uboot_ep, uboot_size);
            STEP("validate_uboot_header", 1, d);
        }
    }

    /* v3.1 banner: printed AFTER validation and BEFORE any device
     * access. If the phone run shows this line and nothing after
     * it, the tool died opening the device or in the FEL_VERSION
     * exchange — not in file validation. */
    emit_json("{\"banner\":true,\"tool\":\"%s\",\"file_size\":%u,"
              "\"file_sha256\":\"%s\",\"spl_len\":%u,\"spl_sha256\":\"%s\","
              "\"uboot_load\":\"0x%08x\",\"uboot_entry\":\"0x%08x\","
              "\"uboot_size\":%u,\"validate_only\":%s}\n",
              tool, (unsigned)file_len, file_sha,
              spl_len, spl_sha, uboot_load, uboot_ep, uboot_size,
              g_validate_only ? "true" : "false");

    /* ---- open the device, prove FEL is alive, H3 only ---- */
    if (fel_open(fd, &dev, err, sizeof(err)) != 0) {
        diag("fel_open", err);
        snprintf(g_error, sizeof(g_error), "%s", err);
        g_failed = 1;
        goto out;
    }
    dev_open = 1;
    {
        unsigned char ver[32];
        uint16_t soc_id;
        /* v3.3.1: retry the FEL_VERSION exchange (3 attempts,
         * 500 ms apart), mirroring the v3.2 eGON.FEL read-back
         * retry. On the phone on 2026-11-19 the flow died here
         * with "FEL_VERSION failed" although direct fel_version
         * had answered 3x minutes earlier on the same device
         * path (001/005): FEL_VERSION is intermittent on this
         * phone, so one dropped bulk reply is weak evidence
         * that FEL is gone. AW_FEL_VERSION is an idempotent
         * query, so re-sending it after a dropped reply is
         * safe. Each failed attempt is logged to stderr; the
         * successful attempt is recorded in the step detail.
         * After 3 failed attempts the error is unchanged, so
         * fel-auto still classifies it as NEED_REENTRY. */
        int attempt, version_ok = 0;
        for (attempt = 1; attempt <= 3; attempt++) {
            if (fel_send_request(&dev, AW_FEL_VERSION, 0, 0) == 0 &&
                fel_read_version_reply(&dev, ver) == 0 &&
                memcmp(ver, "AWUSBFEX", 8) == 0) {
                version_ok = 1;
                break;
            }
            if (attempt < 3) {
                diag("fel_version_soc_check",
                     "FEL_VERSION exchange failed, retrying (dropped bulk reply?)");
                usleep(500000);
            }
        }
        if (!version_ok) {
            diag("fel_version_soc_check",
                 "FEL_VERSION failed: device is not answering in FEL mode (3 attempts)");
            snprintf(g_error, sizeof(g_error),
                     "%s", "FEL_VERSION failed: device is not answering in FEL mode");
            g_failed = 1;
            goto out;
        }
        soc_id = (uint16_t)((fel_get_le32(ver + 8) >> 8) & 0xffff);
        soc_id_checked = soc_id;
        {
            char d[128];
            snprintf(d, sizeof(d), "soc_id 0x%04x (%s), scratchpad 0x%04x (attempt %d of 3)",
                     soc_id, fel_soc_name(soc_id),
                     fel_get_le32(ver + 20) & 0xffffu, attempt);
            STEP("fel_version_soc_check", soc_id == 0x1680, d);
        }
        CHECK(soc_id == 0x1680,
              "only Allwinner H3 (soc_id 0x1680) is supported by this tool");
    }

    /* v3.1 validate-only: stop here — validation + FEL_VERSION /
     * soc check passed, no write or exec has happened. This
     * isolates "tool/transport broken" from "device fails during
     * the SPL/U-Boot flow". */
    if (g_validate_only) {
        STEP("validate_only", 1,
             "validation + FEL_VERSION/soc check passed; no write/exec performed (validate-only mode)");
        rc = 0;
        goto out;
    }

    /* ---- stackinfo (logging only, fel.c L1129) ---- */
    {
        uint32_t sp_irq = 0, sp = 0;
        char d[128];
        if (get_stackinfo(&dev, &sp_irq, &sp) == 0) {
            snprintf(d, sizeof(d), "sp_irq=0x%08x, sp=0x%08x", sp_irq, sp);
            STEP("get_stackinfo", 1, d);
        } else {
            fprintf(stderr, "fel_spl_uboot: warning: step=get_stackinfo failed: scratch code did not return stack pointers (logging only, continuing)\n");
            fflush(stderr);
            STEP("get_stackinfo", 0, "scratch code did not return stack pointers (logging only, continuing)");
        }
    }

    /* ---- MMU: backup (H3: MMU off, expect NULL) + setup ---- */
    {
        /* v3.1: off the stack (static storage; single-threaded
         * tool). v3 had this 16 KiB table on the stack, nested
         * under the 16 KiB raw buffers of the MMU helpers. */
        static uint32_t tt[4096];
        uint32_t sctlr = 0;
        int mmu = backup_and_disable_mmu(&dev, tt, &sctlr);
        char d[160];
        if (mmu < 0) {
            diag("mmu_backup_and_disable",
                 mmu == -2 ? "Unexpected SCTLR (fel.c L975-980)"
                           : "MMU backup failed (fel.c L933-1016)");
            snprintf(g_error, sizeof(g_error),
                     "%s", mmu == -2 ? "Unexpected SCTLR (fel.c L975-980)"
                                    : "MMU backup failed (fel.c L933-1016)");
            g_failed = 1;
            goto out;
        }
        snprintf(d, sizeof(d), "sctlr=0x%08x, mmu_enabled_by_brom=%s",
                 sctlr, mmu ? "yes" : "no");
        STEP("mmu_backup_and_disable", 1, d);
        if (!mmu) {
            /* fel.c L1133-1150: H3 has mmu_tt_addr, so generate a
             * new table at 0x8000. Upstream sets the registers here
             * and writes the table back only in the restore step
             * (fel.c L1018-1076); this tool does the same. */
            CHECK((H3_MMU_TT_ADDR & 0x3FFFu) == 0,
                  "SPL: 'mmu_tt_addr' must be 16K aligned");
            if (set_dacr(&dev, 0x55555555u) != 0) {
                diag("mmu_generate_table", "set DACR failed");
                snprintf(g_error, sizeof(g_error), "%s", "set DACR failed");
                g_failed = 1; goto out;
            }
            if (set_ttbcr(&dev, 0x00000000u) != 0) {
                diag("mmu_generate_table", "set TTBCR failed");
                snprintf(g_error, sizeof(g_error), "%s", "set TTBCR failed");
                g_failed = 1; goto out;
            }
            if (set_ttbr0(&dev, H3_MMU_TT_ADDR) != 0) {
                diag("mmu_generate_table", "set TTBR0 failed");
                snprintf(g_error, sizeof(g_error), "%s", "set TTBR0 failed");
                g_failed = 1; goto out;
            }
            generate_mmu_tt(tt);
            STEP("mmu_generate_table", 1,
                 "new translation table generated for 0x8000 (DACR 0x55555555, TTBCR 0, TTBR0 0x8000); table is written back in the restore step, as upstream does");
        } else {
            /* MMU was enabled: the table read back from the device
             * is the one the restore step writes back. */
            STEP("mmu_generate_table", 1, "MMU was enabled by BROM; using the table read from the device");
        }

        /* ---- SPL piece writes, fel.c L1151-1175 ---- */
        {
            uint32_t cur_addr = H3_SPL_ADDR;
            size_t file_off = 0, remaining = spl_len;
            uint32_t limit = H3_SPL_LEN_LIMIT;
            int i;
            for (i = 0; i < H3_NSWAP; i++) {
                /* fel.c L1153-1156: if a backup buffer sits inside
                 * [spl_addr, spl_addr+limit), shrink the limit.
                 * (The upstream "buf2 >= spl_addr" half is vacuous
                 * for H3, where spl_addr is 0, so it is not repeated
                 * here.) */
                if (H3_SWAP[i].buf2 < H3_SPL_ADDR + limit)
                    limit = H3_SWAP[i].buf2 - H3_SPL_ADDR;
                if (remaining > 0 && cur_addr < H3_SWAP[i].buf1) {
                    uint32_t tmp = H3_SWAP[i].buf1 - cur_addr;
                    char d[160];
                    if (tmp > remaining) tmp = (uint32_t)remaining;
                    if (fel_write_mem(&dev, cur_addr, file + file_off, tmp) != 0) {
                        diag("spl_write_piece", "FEL_WRITE to SRAM failed (device stopped answering?)");
                        snprintf(g_error, sizeof(g_error), "%s", "SPL piece write failed");
                        g_failed = 1;
                        goto out;
                    }
                    snprintf(d, sizeof(d), "wrote %u bytes at 0x%08x (before protected region 0x%08x)",
                             tmp, cur_addr, H3_SWAP[i].buf1);
                    STEP("spl_write_piece", 1, d);
                    cur_addr += tmp; file_off += tmp; remaining -= tmp;
                }
                if (remaining > 0 && cur_addr == H3_SWAP[i].buf1) {
                    uint32_t tmp = H3_SWAP[i].size;
                    char d[160];
                    if (tmp > remaining) tmp = (uint32_t)remaining;
                    if (fel_write_mem(&dev, H3_SWAP[i].buf2, file + file_off, tmp) != 0) {
                        diag("spl_write_piece_backup", "FEL_WRITE to backup SRAM failed (device stopped answering?)");
                        snprintf(g_error, sizeof(g_error), "%s", "SPL backup write failed");
                        g_failed = 1;
                        goto out;
                    }
                    snprintf(d, sizeof(d),
                             "wrote %u bytes for protected region 0x%08x to backup 0x%08x",
                             tmp, H3_SWAP[i].buf1, H3_SWAP[i].buf2);
                    STEP("spl_write_piece_backup", 1, d);
                    cur_addr += tmp; file_off += tmp; remaining -= tmp;
                }
            }
            spl_len_limit = limit;
            if (H3_THUNK_ADDR < spl_len_limit)
                spl_len_limit = H3_THUNK_ADDR;
            CHECK(spl_len <= spl_len_limit, "SPL: too large (fel.c L1181-1187)");
            if (remaining > 0) {
                char d[160];
                if (fel_write_mem(&dev, cur_addr, file + file_off, remaining) != 0) {
                    diag("spl_write_remaining", "FEL_WRITE to SRAM failed (device stopped answering?)");
                    snprintf(g_error, sizeof(g_error), "%s", "SPL remaining write failed");
                    g_failed = 1;
                    goto out;
                }
                snprintf(d, sizeof(d), "wrote remaining %u bytes at 0x%08x",
                         (unsigned)remaining, cur_addr);
                STEP("spl_write_remaining", 1, d);
            }
        }

        /* ---- thunk: build, write, execute, fel.c L1190-1213 ---- */
        {
            uint32_t thunk_size = (uint32_t)(THUNK_WORDS * 4 + 4 +
                                             (H3_NSWAP + 1) * 12);
            unsigned char *tbuf;
            size_t o = 0;
            uint32_t i;
            char d[160];
            CHECK(thunk_size <= H3_THUNK_SIZE, "SPL: bad thunk size");
            tbuf = malloc(thunk_size);
            CHECK(tbuf != NULL, "out of memory (thunk buffer)");
            for (i = 0; i < THUNK_WORDS; i++, o += 4)
                fel_put_le32(tbuf + o, FEL_TO_SPL_THUNK[i]);
            fel_put_le32(tbuf + o, H3_SPL_ADDR); o += 4;
            for (i = 0; i <= (uint32_t)H3_NSWAP; i++, o += 12) {
                fel_put_le32(tbuf + o, H3_SWAP[i].buf1);
                fel_put_le32(tbuf + o + 4, H3_SWAP[i].buf2);
                fel_put_le32(tbuf + o + 8, H3_SWAP[i].size);
            }
            if (fel_write_mem(&dev, H3_THUNK_ADDR, tbuf, thunk_size) != 0 ||
                fel_exec_mem(&dev, H3_THUNK_ADDR) != 0) {
                free(tbuf);
                diag("thunk_exec", "thunk FEL_WRITE/FEL_EXEC failed (device stopped answering during thunk exec?)");
                snprintf(g_error, sizeof(g_error), "%s", "thunk write/exec failed");
                g_failed = 1;
                goto out;
            }
            free(tbuf);
            snprintf(d, sizeof(d),
                     "thunk %u bytes written to 0x%08x and executed (spl_addr 0x%08x, %d swap buffers)",
                     thunk_size, H3_THUNK_ADDR, H3_SPL_ADDR, H3_NSWAP);
            STEP("thunk_exec", 1, d);
        }

        usleep(250000); /* fel.c L1216: TODO workaround delay */

        /* ---- eGON.FEL read-back, fel.c L1219-1225 ---- */
        {
            unsigned char sig[8];
            char d[192];
            /* v3.2: retry the read-back (3 attempts, 500 ms apart)
             * before declaring FEL dead. On the phone on 2026-11-17
             * the single attempt failed with "FEL stopped answering
             * after the thunk" — but FEL_VERSION itself is
             * intermittent on this phone (two identical runs
             * returned nothing, then a third succeeded), so one
             * failed read is weak evidence that FEL is gone. A
             * retry distinguishes a dropped transport run from a
             * truly dead FEL. The 250 ms wait above is upstream
             * fel.c L1216 and is unchanged. */
            int attempt, read_ok = 0;
            for (attempt = 1; attempt <= 3; attempt++) {
                if (fel_read_mem(&dev, H3_SPL_ADDR + 4, sig, sizeof(sig)) == 0) {
                    read_ok = 1;
                    break;
                }
                if (attempt < 3) usleep(500000);
            }
            if (!read_ok) {
                diag("egon_fel_readback", "FEL_READ of SPL header failed after 3 attempts (FEL stopped answering after the thunk)");
                snprintf(g_error, sizeof(g_error), "%s",
                         "SPL: could not read back the SPL header (FEL stopped answering after the thunk, 3 attempts)");
                g_failed = 1;
                goto out;
            }
            snprintf(d, sizeof(d), "header at 0x00000004 reads '%c%c%c%c%c%c%c%c' (attempt %d of 3)",
                     sig[0], sig[1], sig[2], sig[3], sig[4], sig[5], sig[6], sig[7], attempt);
            STEP("egon_fel_readback", memcmp(sig, "eGON.FEL", 8) == 0, d);
            CHECK(memcmp(sig, "eGON.FEL", 8) == 0,
                  "SPL: failure code in header (expected eGON.FEL, fel.c L1221)");
        }

        /* ---- MMU restore, fel.c L1227-1228 ---- */
        {
            int r = restore_and_enable_mmu(&dev, tt);
            if (r != 0) {
                diag("mmu_restore_and_enable",
                     r == -2 ? "MMU restore refused: TTBR0 is 0"
                             : "MMU restore failed (fel.c L1018-1076)");
                snprintf(g_error, sizeof(g_error), "%s",
                         r == -2 ? "MMU restore refused: TTBR0 is 0"
                                 : "MMU restore failed (fel.c L1018-1076)");
                g_failed = 1;
                goto out;
            }
            STEP("mmu_restore_and_enable", 1,
                 "generated table written back, I-cache/MMU/branch prediction re-enabled");
        }
    }

    /* ---- U-Boot proper staging, aw_fel_write_uboot_image ----
     * fel.c L1238-1296 writes the payload in ONE FEL_WRITE.
     * Deviation (documented): this tool writes it in 64 KiB
     * FEL_WRITE chunks instead, because fel_common's bulk
     * transfer timeout is 5000 ms per transfer (upstream uses
     * 60000 ms) and a single 526 KiB transfer could time out on
     * the phone. The bytes landing in DRAM are identical. */
    {
        const unsigned char *payload = file + H3_SPL_LEN_LIMIT + HEADER_SIZE;
        uint32_t off = 0;
        unsigned chunks = 0;
        while (off < uboot_size) {
            uint32_t n = uboot_size - off;
            if (n > UB_CHUNK) n = UB_CHUNK;
            if (fel_write_mem(&dev, uboot_load + off, payload + off, n) != 0) {
                diag("uboot_stage", "DRAM FEL_WRITE failed (DRAM may not be initialised: SPL may have failed to init DRAM)");
                snprintf(g_error, sizeof(g_error), "%s",
                         "U-Boot staging write failed (DRAM may not be initialised: SPL may have failed to init DRAM)");
                g_failed = 1;
                goto out;
            }
            off += n;
            chunks++;
        }
        {
            char d[160];
            snprintf(d, sizeof(d), "staged %u bytes to DRAM 0x%08x in %u chunks of up to 64 KiB",
                     uboot_size, uboot_load, chunks);
            STEP("uboot_stage", 1, d);
        }
    }

    /* ---- U-Boot exec, fel.c L1748-1763 ("uboot" command) ----
     * Upstream executes uboot_entry (== load address here) on
     * exit. The exec request itself must be accepted (AWUS
     * reply); the 8-byte FEL status afterwards is NOT expected,
     * because U-Boot takes over the CPU and never returns to FEL.
     * A status timeout is therefore reported as success-with-note,
     * not as a failure. */
    {
        char d[192];
        if (fel_send_request(&dev, AW_FEL_1_EXEC, uboot_load, 0) != 0) {
            diag("uboot_exec", "U-Boot exec request was not accepted by FEL");
            snprintf(g_error, sizeof(g_error), "%s", "U-Boot exec request was not accepted by FEL");
            g_failed = 1;
            goto out;
        }
        if (fel_read_status(&dev) == 0) {
            snprintf(d, sizeof(d),
                     "exec sent to 0x%08x and a FEL status came back (U-Boot did not take over?)",
                     uboot_load);
            STEP("uboot_exec", 1, d);
        } else {
            snprintf(d, sizeof(d),
                     "exec sent to 0x%08x, no FEL status reply (expected: U-Boot takes over). Re-check FEL_VERSION: a reply means U-Boot did not take over.",
                     uboot_load);
            STEP("uboot_exec", 1, d);
        }
    }

    rc = 0;

out:
    if (g_failed) {
        int r = fail_json(tool, g_error[0] ? g_error : "unknown error",
                          file_sha, (uint32_t)file_len);
        free(file);
        if (dev_open) fel_close(&dev);
        return r;
    }
    if (g_validate_only) {
        /* Validate-only success: no SPL/U-Boot flow ran, so there
         * is no eGON.FEL and no U-Boot exec to report. */
        emit_json("{\"ok\":true,\"tool\":\"%s\",\"version\":1,"
                  "\"validate_only\":true,"
                  "\"file_sha256\":\"%s\",\"file_size\":%u,"
                  "\"spl_len\":%u,\"spl_sha256\":\"%s\","
                  "\"uboot_load\":\"0x%08x\",\"uboot_entry\":\"0x%08x\",\"uboot_size\":%u,"
                  "\"soc_id\":\"0x%04x\","
                  "\"bulk_ep_out\":%d,\"bulk_ep_in\":%d,"
                  "\"vid\":\"0x%04x\",\"pid\":\"0x%04x\",\"verified_on_device\":true,"
                  "\"steps\":[%s],"
                  "\"note\":\"Validate-only: file validation + FEL_VERSION/soc check passed; no write or exec was performed.\"}\n",
                  tool, file_sha, (unsigned)file_len,
                  spl_len, spl_sha,
                  uboot_load, uboot_ep, uboot_size,
                  soc_id_checked,
                  dev.bulk_ep_out, dev.bulk_ep_in, dev.vid, dev.pid,
                  g_steps);
        free(file);
        if (dev_open) fel_close(&dev);
        return rc;
    }
    emit_json("{\"ok\":true,\"tool\":\"%s\",\"version\":1,"
              "\"file_sha256\":\"%s\",\"file_size\":%u,"
              "\"spl_len\":%u,\"spl_sha256\":\"%s\","
              "\"uboot_load\":\"0x%08x\",\"uboot_entry\":\"0x%08x\",\"uboot_size\":%u,"
              "\"egon_fel\":true,\"uboot_exec_sent\":true,"
              "\"bulk_ep_out\":%d,\"bulk_ep_in\":%d,"
              "\"vid\":\"0x%04x\",\"pid\":\"0x%04x\",\"verified_on_device\":true,"
              "\"steps\":[%s],"
              "\"note\":\"U-Boot proper staged in DRAM and executed; it may never return a FEL status. Re-check FEL_VERSION: a reply means U-Boot did not take over.\"}\n",
              tool, file_sha, (unsigned)file_len,
              spl_len, spl_sha,
              uboot_load, uboot_load, uboot_size,
              dev.bulk_ep_out, dev.bulk_ep_in, dev.vid, dev.pid,
              g_steps);
    free(file);
    if (dev_open) fel_close(&dev);
    return rc;
}
