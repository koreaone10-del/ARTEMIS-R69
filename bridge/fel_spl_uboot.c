/* H3 swap buffers (fel.c L482-490, a10_a13_a20_sram_swap_buffers,
 * used by the H3 entry, fel.c L603-608):
 *   BROM buffer (buf1) -> backup storage (buf2), size
 *   0x1C00-0x1FFF IRQ stack  -> 0xA400, 0x0400
 *   0x5C00-0x6FFF stack      -> 0xA800, 0x1400
 *   0x7C00-0x7FFF important  -> 0xBC00, 0x0400
 * Entries must be sorted by buf1 (fel.c L444-446). */
typedef struct { uint32_t buf1, buf2, size; } swap_buf_t;
static const swap_buf_t H3_SWAP[] = {
    { 0x00001C00u, 0x0000A400u, 0x00000400u },
    { 0x00005C00u, 0x0000A800u, 0x00001400u },
    { 0x00007C00u, 0x0000BC00u, 0x00000400u },
    { 0, 0, 0 }, /* terminator, fel.c L489 */
};
#define H3_NSWAP 3

