/* ---------- step log (JSON, built in memory, printed once) ----------
 * v3.1: every step is ALSO printed immediately as a one-line
 * progress JSON object (fflush), and stdout is unbuffered (see
 * main), so a crash/kill later in the flow cannot erase the steps
 * that already completed. The final JSON (with the full steps
 * array) is still printed as the last line.
 * v3.2: emit_json mirrors every line to stderr too (see above):
 * the phone lost the full flow's stdout entirely on 2026-11-17. */
static char g_steps[16384];
static size_t g_steps_len = 0;
static int g_nsteps = 0;
static int g_validate_only = 0;

/* Short stderr diagnostic for a failed step. stderr is NOT the
 * JSON channel, so a line here can never corrupt the final JSON;
 * it is the only trace left if the process is killed right after
 * the failure. */
static void diag(const char *step, const char *reason)
{
    fprintf(stderr, "fel_spl_uboot: step=%s failed: %s\n",
            step ? step : "?", reason ? reason : "");
    fflush(stderr);
}

/* v3.2: emit one JSON line to stdout AND stderr. On the phone on
 * 2026-11-17 the full flow's stdout was lost entirely (the bridge
 * reported stdout "" and progress []), while stderr survived (it
 * carried the egon_fel_readback diag) — so stdout alone cannot be
 * trusted for the long flow. Every JSON line this tool prints
 * (progress, banner, final result) therefore goes to both
 * streams; the server parses progress/banner/final from either.
 * stderr is never parsed as the JSON channel, so the mirror
 * cannot corrupt the result. In a plain terminal each line
 * appears twice; that is cosmetic and worth the diagnosis. */
static void emit_json(const char *fmt, ...)
{
    va_list ap;
    va_start(ap, fmt);
    vfprintf(stdout, fmt, ap);
    va_end(ap);
    fflush(stdout);
    va_start(ap, fmt);
    vfprintf(stderr, fmt, ap);
    va_end(ap);
    fflush(stderr);
}

static void json_escape_into(char *dst, size_t dst_len, const char *src)
{
    size_t i = 0, j = 0;
    if (!src) src = "";
    while (src[i] && j + 2 < dst_len) {
        unsigned char c = (unsigned char)src[i++];
        if (c == '"' || c == '\\') { dst[j++] = '\\'; dst[j++] = (char)c; }
        else if (c < 0x20) { dst[j++] = ' '; }
        else dst[j++] = (char)c;
    }
    dst[j] = '\0';
}

static void step_log(const char *name, int ok, const char *detail)
{
    char esc[1024];
    char tmp[1400];
    json_escape_into(esc, sizeof(esc), detail ? detail : "");
    snprintf(tmp, sizeof(tmp), "%s{\"step\":%d,\"name\":\"%s\",\"ok\":%s,\"detail\":\"%s\"}",
             g_nsteps ? "," : "", g_nsteps, name, ok ? "true" : "false", esc);
    size_t n = strlen(tmp);
    if (g_steps_len + n + 1 < sizeof(g_steps)) {
        memcpy(g_steps + g_steps_len, tmp, n + 1);
        g_steps_len += n;
    }
    /* v3.1: print the step immediately, so it survives a later
     * crash/kill. This line is a progress line, not the final
     * result; parsers must take the LAST line as the result.
     * v3.2: emit_json mirrors it to stderr too — on the phone
     * the full flow's stdout was lost entirely on 2026-11-17. */
    emit_json("{\"progress\":true,\"step\":%d,\"name\":\"%s\",\"ok\":%s,\"detail\":\"%s\"}\n",
              g_nsteps, name, ok ? "true" : "false", esc);
    g_nsteps++;
}

static int fail_json(const char *tool, const char *error,
                     const char *file_sha, uint32_t file_size)
{
    char esc[512];
    json_escape_into(esc, sizeof(esc), error);
    emit_json("{\"ok\":false,\"tool\":\"%s\",\"version\":1,"
              "\"validate_only\":%s,"
              "\"file_sha256\":\"%s\",\"file_size\":%u,"
              "\"steps\":[%s],\"error\":\"%s\"}\n",
              tool, g_validate_only ? "true" : "false",
              file_sha ? file_sha : "", file_size,
              g_steps, esc);
    return 1;
}

/* ---------- file / header helpers ---------- */
static uint32_t be32(const unsigned char *p)
{
    return ((uint32_t)p[0] << 24) | ((uint32_t)p[1] << 16) |
           ((uint32_t)p[2] << 8) | (uint32_t)p[3];
}

static unsigned char *read_all_file(const char *path, size_t *out_len)
{
    FILE *in = fopen(path, "rb");
    size_t cap = 65536, len = 0;
    unsigned char *buf;
    if (!in)
        return NULL;
    /* v3.1: refuse oversize files BEFORE allocating/growing a
     * buffer for them (a multi-MiB file must not be read fully
     * just to be refused by the caller afterwards). */
    if (fseek(in, 0, SEEK_END) == 0) {
        long sz = ftell(in);
        if (sz < 0 || (uint64_t)sz > UB_MAX_FILE) { fclose(in); return NULL; }
        if (fseek(in, 0, SEEK_SET) != 0) { fclose(in); return NULL; }
    }
    buf = malloc(cap);
    if (!buf) { fclose(in); return NULL; }
    for (;;) {
        size_t want = cap - len, n;
        if (want == 0) {
            unsigned char *nb;
            cap *= 2;
            nb = realloc(buf, cap);
            if (!nb) { free(buf); fclose(in); return NULL; }
            buf = nb;
            want = cap - len;
        }
        n = fread(buf + len, 1, want, in);
        len += n;
        if (n < want)
            break;
    }
    fclose(in);
    *out_len = len;
    return buf;
}

/* eGON checksum, exactly as fel.c L1102-1117:
 *   spl_checksum = 2 * le32(buf32[3]) - 0x5F0A6C39;
 *   for each LE32 word of the SPL: spl_checksum -= word;
 *   result must be 0. (buf32[3] is the checksum field itself,
 *   byte offset 12.) */
static int egon_checksum_ok(const unsigned char *buf, uint32_t spl_len)
{
    uint32_t c = 2 * fel_get_le32(buf + 12) - 0x5F0A6C39u;
    uint32_t i;
    for (i = 0; i < spl_len / 4; i++)
        c -= fel_get_le32(buf + i * 4);
    return c == 0;
}

/* ---------- scratch-code helpers (fel.c L673-1076) ----------
 * Upstream runs tiny ARM code snippets at scratch_addr (0x1000)
 * via FEL_WRITE + FEL_EXEC, then reads the result back with
 * FEL_READ. All code words below are copied from fel.c; the
 * comments give the fel.c line ranges. fel_common's
 * fel_write_mem / fel_exec_mem / fel_read_mem are the transport
 * (FEL_WRITE / FEL_EXEC / FEL_READ + status, same order as
 * upstream aw_fel_write / aw_fel_execute / aw_fel_read). */

/* aw_read_arm_cp_reg, fel.c L673-692: mrc coproc,opc1,r0,crn,crm,opc2;
 * str r0,[pc]; bx lr. Result is read at scratch+12. */
static int read_cp_reg(fel_device *dev, uint32_t coproc, uint32_t opc1,
                       uint32_t crn, uint32_t crm, uint32_t opc2,
                       uint32_t *out)
{
    uint32_t opcode = 0xEE000000u | (1u << 20) | (1u << 4) |
                      ((opc1 & 7u) << 21) | ((crn & 15u) << 16) |
                      ((coproc & 15u) << 8) | ((opc2 & 7u) << 5) |
                      (crm & 15u);
    unsigned char code[12], val[4];
    fel_put_le32(code + 0, opcode);
    fel_put_le32(code + 4, 0xe58f0000u); /* str r0, [pc] */
    fel_put_le32(code + 8, 0xe12fff1eu); /* bx lr */
    if (fel_write_mem(dev, H3_SCRATCH_ADDR, code, sizeof(code)) != 0)
        return -1;
    if (fel_exec_mem(dev, H3_SCRATCH_ADDR) != 0)
        return -1;
    if (fel_read_mem(dev, H3_SCRATCH_ADDR + 12, val, sizeof(val)) != 0)
        return -1;
    *out = fel_get_le32(val);
    return 0;
}

/* aw_write_arm_cp_reg, fel.c L695-716: ldr r0,[pc,#12]; mcr ...;
 * dsb; isb; bx lr; <value>. */
static int write_cp_reg(fel_device *dev, uint32_t coproc, uint32_t opc1,
                        uint32_t crn, uint32_t crm, uint32_t opc2,
                        uint32_t val)
{
    uint32_t opcode = 0xEE000000u | (0u << 20) | (1u << 4) |
                      ((opc1 & 7u) << 21) | ((crn & 15u) << 16) |
                      ((coproc & 15u) << 8) | ((opc2 & 7u) << 5) |
                      (crm & 15u);
    unsigned char code[24];
    fel_put_le32(code + 0, 0xe59f000cu); /* ldr r0, [pc, #12] */
    fel_put_le32(code + 4, opcode);      /* mcr coproc, ... */
    fel_put_le32(code + 8, 0xf57ff04fu); /* dsb sy */
    fel_put_le32(code + 12, 0xf57ff06fu); /* isb sy */
    fel_put_le32(code + 16, 0xe12fff1eu); /* bx lr */
    fel_put_le32(code + 20, val);
    if (fel_write_mem(dev, H3_SCRATCH_ADDR, code, sizeof(code)) != 0)
        return -1;
    return fel_exec_mem(dev, H3_SCRATCH_ADDR);
}

