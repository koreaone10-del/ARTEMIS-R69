/*
 * fel_spl_uboot.c -- upstream-style Allwinner FEL SPL + U-Boot loader
 * (ARTEMIS Termux bridge v3.1)
 *
 * v3.1 (2026-11-17): the v3 tool printed NOTHING on the user's
 * phone — neither via the bridge page nor via a direct Termux run
 * (fel_spl_uboot_bad_output, empty stdout, only locale warnings
 * on stderr) — and FEL_VERSION itself was intermittent on that
 * phone (same command: success, then twice no output at all, then
 * success again). Audit finding (see bridge/docs/SOURCES.md §6):
 * no deterministic crash was found in the validation / fel_open
 * paths — in the VM the v3 binary prints all four validation
 * steps plus a fel_open failure for a bad fd — and no buffer
 * overflow was found (all stack buffers are sized correctly, the
 * thunk loop i<=H3_NSWAP is correct because it must include the
 * {0,0,0} terminator). The silent death is therefore most likely
 * a device-side hang/kill or a lost stdout in the termux-usb /
 * Termux:API path, made undiagnosable by the v3 design: the step
 * log was built in memory and printed ONLY at the end, and stdout
 * was fully buffered (a pipe), so a kill at any point lost every
 * step, including the four validation steps that had already
 * passed. v3.1 fixes the diagnosability, not a specific crash:
 *   - every STEP() also prints a one-line progress JSON object
 *     immediately and fflush(stdout);
 *   - stdout is set unbuffered (setvbuf _IONBF) at startup;
 *   - a banner line is printed after file validation, before
 *     touching the device;
 *   - --validate-only (or FEL_VALIDATE_ONLY=1) validates the
 *     file + FEL_VERSION/soc check and exits without any
 *     write/exec, isolating tool crashes from device failures;
 *   - failure paths print a short "step=... failed: ..." line
 *     to stderr;
 *   - the 16 KiB MMU table and the 16 KiB raw MMU buffers are
 *     moved off the stack (static storage) — the largest latent
 *     stack-overflow risk in v3 (tt[4096] in main + raw[16384]
 *     nested inside backup/restore).
 *
 * SPDX-License-Identifier: GPL-2.0-or-later
 * Copyright (C) 2026 ARTEMIS R69 project contributors
 *
 * This tool performs, in one process, the two upstream sunxi-fel
 * operations that the v2 bridge could not do safely:
 *   1. aw_fel_write_and_execute_spl()  (fel.c L1078-1235)
 *   2. aw_fel_write_uboot_image()     (fel.c L1238-1296)
 * as called by aw_fel_process_spl_and_uboot() (fel.c L1300-1313),
 * followed by executing the staged U-Boot proper, as sunxi-fel's
 * "uboot" command does (fel.c L1748-1763).
 *
 * Why v3 exists: the v2 bridge wrote an SPL raw to 0x00000000 with
 * FEL_WRITE and executed it at 0x0. On 2026-11-17 that killed FEL
 * mid-transfer on the user's R69 (FEL_VERSION then produced no
 * output at all; the device had to be re-entered into FEL). The
 * cause is the one documented in bridge/docs/SOURCES.md §6: the
 * SPL overwrites the BROM's own IRQ stack (0x1C00), stack
 * (0x5C00) and "something important" region (0x7C00-0x7FFF) while
 * FEL is still using them. Upstream avoids that by writing the
 * SPL pieces that fall on those regions to backup SRAM instead
 * (0xA400 / 0xA800 / 0xBC00) and running a thunk at 0xA200 that
 * swaps the regions in, verifies the eGON checksum, jumps to the
 * SPL, and swaps the regions back before returning to FEL.
 * This tool implements that path faithfully; see
 * bridge/docs/SOURCES.md §6 for the step-by-step record with
 * fel.c line references.
 *
 * Wire format / protocol facts (not copied code): sunxi-tools,
 * fel.c (Icenowy/sunxi-tools master),
 * Copyright (C) 2012 Henrik Nordstrom and contributors, GPL-2.0.
 *
 * The thunk code below is the fel_to_spl_thunk array from
 * sunxi-tools fel-to-spl-thunk.h, generated by
 *   ruby -x fel-to-spl-thunk.S > fel-to-spl-thunk.h
 * (source: https://raw.githubusercontent.com/Icenowy/sunxi-tools/master/fel-to-spl-thunk.h ;
 *  assembly source fel-to-spl-thunk.S, Copyright (C) 2015 Siarhei
 *  Siamashka, MIT licence). The 66 words are copied verbatim;
 *  nothing about them was invented or re-derived here.
 *
 * Usage (Termux, no root):
 *   termux-usb -r -e ./bridge/fel_spl_uboot /path/u-boot-sunxi-with-spl.bin /dev/bus/usb/001/002
 *   # or, with -E:
 *   TERMUX_USB_FD=<fd> ./bridge/fel_spl_uboot /path/file
 *   FEL_FILE=/path/file ./bridge/fel_spl_uboot <fd>
 *   ./bridge/fel_spl_uboot --validate-only /path/file
 *     (or FEL_VALIDATE_ONLY=1): validate the file, open the
 *     device and check FEL_VERSION/soc, then exit WITHOUT any
 *     write or exec. Use this first on the phone: if it prints
 *     validation steps + a fel_open/FEL_VERSION result, the tool
 *     and the transport work and a later silence is a
 *     device-side failure during the flow, not a tool crash.
 *
 * The program takes a USB file descriptor (argv[1], last argv
 * token, or $TERMUX_USB_FD) and one file argument, and prints
 * exactly one JSON object to stdout, including a per-step log.
 * v3.1 ALSO prints one progress JSON line per step, immediately,
 * plus a banner line after validation, so a later crash or kill
 * still leaves the completed steps visible. v3.2 mirrors every
 * JSON line (progress, banner, final result) to stderr as well,
 * and retries the eGON.FEL read-back 3 times: on the phone on
 * 2026-11-17 the full flow's stdout was lost entirely while
 * stderr survived, and FEL_VERSION itself is intermittent
 * there. Parse stdout (or stderr) by lines: progress lines have
 * "progress":true, the banner has "banner":true, and the LAST
 * line is the final result object ({"ok":...}).
 *
 * Safety: H3 only (soc_id 0x1680, verified live via FEL_VERSION
 * before any write). SPL is written only to SRAM 0x00000000 with
 * the upstream swap/thunk; U-Boot proper is written only to the
 * DRAM load address in its own mkimage header. It never writes
 * eMMC, NAND or flash. A U-Boot exec that takes over the device
 * never returns a FEL status; that is reported as
 * "uboot_exec_sent, no FEL reply expected", not as a failure.
 *
 * LIVE RUN 2026-11-17 (v3.1): validate-only passed on the phone
 * (all 4 validation steps + FEL_VERSION 0x1680/H3), but the full
 * flow failed at egon_fel_readback — "FEL_READ of SPL header
 * failed (FEL stopped answering after the thunk)" — with stdout
 * entirely lost (empty stdout, progress []) and only the stderr
 * diag surviving. Whether FEL really died or the transport
 * dropped the read is still open: FEL_VERSION is intermittent
 * on this phone. v3.2 answers exactly that (stderr mirror +
 * 3-attempt read-back). v3.3.1 answers the same question one
 * step earlier: on 2026-11-19 the flow died at step 4
 * fel_version_soc_check ("FEL_VERSION failed") although direct
 * fel_version had answered 3x minutes earlier on the same
 * device path (001/005) — so the version exchange itself is
 * retried 3 times, 500 ms apart, like the eGON read-back.
 * The exchange order, swap table, thunk bytes, MMU handling
 * and eGON checks are verified against fel.c source only; no
 * run has yet returned eGON.FEL. See bridge/README.md for the
 * phone test plan.
 */

